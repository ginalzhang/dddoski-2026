import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import {
  generateFunQuiz,
  discoverFunFeed,
  prefetchTranscripts,
  validateQuiz,
  shuffleQuiz,
  recordSpend,
  spendToday,
  runActor,
  ApifyError,
  SpendCapError,
  QuizPolicyError,
  parseSources,
  __resetSpend,
  __resetTranscripts,
  __resetDiscovery,
  type QuizClient,
} from "@/lib/server/generated";

const GOOD = {
  question: "What did the chef add last?",
  options: ["Salt", "Lemon zest", "Basil", "Olive oil"],
  correct_index: 1,
  rationale: "Said at the end.",
};

function mockClient(...responses: Array<unknown | Error>): QuizClient & { calls: unknown[] } {
  const calls: unknown[] = [];
  let i = 0;
  return {
    calls,
    messages: {
      parse: vi.fn(async (params: unknown) => {
        calls.push(params);
        const r = responses[Math.min(i++, responses.length - 1)];
        if (r instanceof Error) throw r;
        return r as never;
      }),
    },
  };
}
const ok = (q = GOOD) => ({ stop_reason: "end_turn", parsed_output: q, usage: { input_tokens: 1000, output_tokens: 100 } });
const refusal = { stop_reason: "refusal", parsed_output: null, usage: { input_tokens: 10, output_tokens: 1 } };

function jsonRes(body: unknown, status = 200) {
  return new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });
}

const envBackup = { ...process.env };
beforeEach(() => {
  __resetSpend();
  __resetTranscripts();
  __resetDiscovery();
  process.env.APIFY_TOKEN = "test-token";
  delete process.env.NO_TRANSCRIPT_POLICY;
  delete process.env.DAILY_SPEND_CAP_USD;
});
afterEach(() => {
  process.env = { ...envBackup };
});

const noStore = async () => null;
const storeHit = async () => ({ text: "The chef adds lemon zest at the end.", lang: "en", isAutoGenerated: true });

describe("fallback ladder", () => {
  it("cached transcript from store → LLM quiz (no Apify call), options shuffled with correct index tracked", async () => {
    const fetch = vi.fn();
    const client = mockClient(ok());
    const r = await generateFunQuiz("abcdefghijk", { title: "Cooking" }, { client, fetch, getCachedTranscript: storeHit, random: () => 0 });
    expect(fetch).not.toHaveBeenCalled();
    expect("pass" in r).toBe(false);
    if ("pass" in r) return;
    expect(r.options[r.correctIndex]).toBe("Lemon zest");
    expect(new Set(r.options)).toEqual(new Set(GOOD.options));
    const params = client.calls[0] as { model: string; max_tokens: number; output_config: { effort: string }; messages: { content: string }[] };
    expect(params.model).toBe("claude-opus-5-5");
    expect(params.max_tokens).toBe(1024);
    expect(params.output_config.effort).toBe("low");
    expect(params.messages[0].content).toContain("auto-generated");
    expect(spendToday().quizzes).toBe(1);
    expect(spendToday().llmUsd).toBeGreaterThan(0);
  });

  it("accepts the store's VideoRow shape", async () => {
    const client = mockClient(ok());
    const row = async () => ({ video_id: "abcdefghijk", transcript_text: "Bonjour", transcript_lang: "fr", transcript_auto: false } as never);
    const r = await generateFunQuiz("abcdefghijk", {}, { client, getCachedTranscript: row });
    expect("question" in r).toBe(true);
    expect((client.calls[0] as { messages: { content: string }[] }).messages[0].content).toContain("Transcript language: fr");
  });

  it("no store transcript → Apify transcript → LLM", async () => {
    const fetch = vi.fn(async (url: string, init?: RequestInit) => {
      expect(url).toContain("devsef~youtube-transcript-scraper/run-sync-get-dataset-items?maxTotalChargeUsd=");
      expect((init!.headers as Record<string, string>).Authorization).toBe("Bearer test-token");
      expect(JSON.parse(init!.body as string).videoUrls).toEqual(["abcdefghijk"]);
      return jsonRes([{ videoId: "abcdefghijk", status: "ok", text: "hello world", language: "en", isAutoGenerated: false }]);
    });
    const client = mockClient(ok());
    const r = await generateFunQuiz("abcdefghijk", {}, { client, fetch, getCachedTranscript: noStore });
    expect(fetch).toHaveBeenCalledTimes(1);
    expect("question" in r).toBe(true);
  });

  it("LLM refusal → retry → refusal → metadata quiz", async () => {
    const client = mockClient(refusal, refusal, ok());
    const r = await generateFunQuiz("abcdefghijk", { title: "Cat jumps", channel: "Cats" }, { client, getCachedTranscript: storeHit });
    expect(client.calls).toHaveLength(3);
    expect((client.calls[2] as { messages: { content: string }[] }).messages[0].content).toContain("No transcript is available");
    expect("question" in r).toBe(true);
  });

  it("refusal then success on retry stays on the transcript rung", async () => {
    const client = mockClient(refusal, ok());
    const r = await generateFunQuiz("abcdefghijk", { title: "x" }, { client, getCachedTranscript: storeHit });
    expect(client.calls).toHaveLength(2);
    expect((client.calls[1] as { messages: { content: string }[] }).messages[0].content).toContain("<transcript>");
    expect("question" in r).toBe(true);
  });

  it("retries once on 429 and on invalid output", async () => {
    const rl = Object.assign(new Error("rate limited"), { status: 429 });
    const client = mockClient(rl, ok({ ...GOOD, options: ["a", "a", "b", "c"] }), ok());
    const r = await generateFunQuiz("abcdefghijk", { title: "t" }, { client, getCachedTranscript: storeHit });
    // 429 + retry(invalid) exhaust transcript rung; metadata rung succeeds.
    expect(client.calls).toHaveLength(3);
    expect("question" in r).toBe(true);
  });

  it("no transcript + metadata fails → pass", async () => {
    const fetch = vi.fn(async () => jsonRes([{ videoId: "abcdefghijk", status: "no_transcript" }]));
    const client = mockClient(refusal);
    const r = await generateFunQuiz("abcdefghijk", { title: "t" }, { client, fetch, getCachedTranscript: noStore });
    expect(r).toEqual({ pass: true });
    expect(client.calls).toHaveLength(2); // metadata rung only, with one retry
  });

  it("no transcript and no title → pass without calling LLM", async () => {
    const fetch = vi.fn(async () => jsonRes([], 402));
    const client = mockClient(ok());
    const r = await generateFunQuiz("abcdefghijk", undefined, { client, fetch, getCachedTranscript: noStore });
    expect(r).toEqual({ pass: true });
    expect(client.calls).toHaveLength(0);
  });

  it("fail-closed throws when nothing works", async () => {
    process.env.NO_TRANSCRIPT_POLICY = "fail-closed";
    const fetch = vi.fn(async () => jsonRes([{ videoId: "abcdefghijk", status: "no_transcript" }]));
    const client = mockClient(ok());
    await expect(generateFunQuiz("abcdefghijk", { title: "t" }, { client, fetch, getCachedTranscript: noStore })).rejects.toBeInstanceOf(
      QuizPolicyError,
    );
    expect(client.calls).toHaveLength(0); // fail-closed skips the metadata rung
  });
});

describe("spend cap", () => {
  it("over cap skips Apify and LLM and goes to policy", async () => {
    process.env.DAILY_SPEND_CAP_USD = "1";
    recordSpend({ apifyUsd: 0.6, llmUsd: 0.5 });
    expect(spendToday().totalUsd).toBeCloseTo(1.1);
    const fetch = vi.fn();
    const client = mockClient(ok());
    expect(await generateFunQuiz("abcdefghijk", { title: "t" }, { client, fetch, getCachedTranscript: storeHit })).toEqual({ pass: true });
    expect(fetch).not.toHaveBeenCalled();
    expect(client.calls).toHaveLength(0);
    await prefetchTranscripts(["abcdefghijk"], { fetch });
    expect(fetch).not.toHaveBeenCalled();
    process.env.FUN_SOURCES = "keyword:cats";
    await expect(discoverFunFeed(null, { fetch, onPage: () => {} })).rejects.toBeInstanceOf(SpendCapError);
  });

  it("default cap is 5 USD", async () => {
    recordSpend({ llmUsd: 4.99 });
    const client = mockClient(ok());
    const r = await generateFunQuiz("abcdefghijk", {}, { client, getCachedTranscript: storeHit });
    expect("question" in r).toBe(true);
  });
});

describe("Apify errors", () => {
  it.each([
    [402, "payment"],
    [408, "timeout"],
    [500, "error"],
  ])("HTTP %i → ApifyError(%s)", async (status, kind) => {
    const fetch = vi.fn(async () => jsonRes({ error: "x" }, status));
    const err = await runActor("a~b", {}, { fetch, maxChargeUsd: 0.1 }).catch((e) => e);
    expect(err).toBeInstanceOf(ApifyError);
    expect(err.kind).toBe(kind);
  });

  it("aborts after timeout", async () => {
    const fetch = vi.fn(
      (_u: string, init?: RequestInit) =>
        new Promise<Response>((_, rej) => init!.signal!.addEventListener("abort", () => rej(Object.assign(new Error("aborted"), { name: "AbortError" })))),
    );
    const err = await runActor("a~b", {}, { fetch, maxChargeUsd: 0.1, timeoutMs: 20 }).catch((e) => e);
    expect(err.kind).toBe("timeout");
  });

  it("blocked transcript items are not cached (retry later), quiz falls through", async () => {
    let n = 0;
    const fetch = vi.fn(async () => (n++, jsonRes([{ videoId: "abcdefghijk", status: "blocked" }])));
    const client = mockClient(refusal);
    expect(await generateFunQuiz("abcdefghijk", {}, { client, fetch, getCachedTranscript: noStore })).toEqual({ pass: true });
    await generateFunQuiz("abcdefghijk", {}, { client, fetch, getCachedTranscript: noStore });
    expect(n).toBe(2);
  });

  it("discovery: 402 from every source throws typed error; partial failure still serves", async () => {
    process.env.FUN_SOURCES = "channel:@MrBeast,keyword:satisfying,hashtag:shorts";
    const all402 = vi.fn(async () => jsonRes({}, 402));
    const err = await discoverFunFeed(null, { fetch: all402, onPage: () => {} }).catch((e) => e);
    expect(err).toBeInstanceOf(ApifyError);
    expect(err.kind).toBe("payment");

    const bodies: Record<string, unknown>[] = [];
    const mixed = vi.fn(async (url: string, init?: RequestInit) => {
      bodies.push(JSON.parse(init!.body as string));
      if (url.includes("streamers~")) return jsonRes([{ id: "AAAAAAAAAAA", title: "A" }, { id: "BBBBBBBBBBB", title: "B" }]);
      if (url.includes("makework36~")) return jsonRes([{ videoId: "AAAAAAAAAAA", title: "A dup" }, { videoId: "CCCCCCCCCCC", title: "C" }]);
      return jsonRes({}, 408);
    });
    const page1 = await discoverFunFeed(null, { fetch: mixed, onPage: () => {} });
    expect(page1.items.map((i) => i.videoId)).toEqual(["AAAAAAAAAAA", "BBBBBBBBBBB", "CCCCCCCCCCC"]);
    expect(page1.cursor).toBeNull();
    expect(bodies).toContainEqual(expect.objectContaining({ channels: ["MrBeast"] }));
    expect(bodies).toContainEqual(expect.objectContaining({ searchQueries: ["satisfying"] }));
    expect(bodies).toContainEqual(expect.objectContaining({ hashtagKeywords: ["shorts"] }));
  });

  it("discovery paginates via cursor and serves from cache", async () => {
    process.env.FUN_SOURCES = "hashtag:cats";
    const ids = ["a", "b", "c", "d", "e"].map((c) => c.repeat(11));
    const fetch = vi.fn(async () => jsonRes(ids.map((id) => ({ "Short/Video ID": id, Title: id }))));
    const p1 = await discoverFunFeed(null, { fetch, onPage: () => {} });
    expect(p1.items).toHaveLength(3);
    const p2 = await discoverFunFeed(p1.cursor, { fetch, onPage: () => {} });
    expect(p2.items.map((i) => i.videoId)).toEqual(ids.slice(3));
    expect(p2.cursor).toBeNull();
    expect(fetch).toHaveBeenCalledTimes(1);
  });

  it("prefetch batches up to 200 IDs per run", async () => {
    const sizes: number[] = [];
    const fetch = vi.fn(async (_u: string, init?: RequestInit) => {
      const ids = JSON.parse(init!.body as string).videoUrls as string[];
      sizes.push(ids.length);
      return jsonRes(ids.map((videoId) => ({ videoId, status: "ok", text: "t" })));
    });
    const ids = Array.from({ length: 450 }, (_, i) => String(i).padStart(11, "x"));
    await prefetchTranscripts(ids, { fetch });
    expect(sizes).toEqual([200, 200, 50]);
  });
});

describe("validation and shuffle", () => {
  it("rejects bad quizzes", () => {
    expect(typeof validateQuiz({ ...GOOD, options: ["a", "b", "c"] })).toBe("string");
    expect(typeof validateQuiz({ ...GOOD, options: ["a", " ", "c", "d"] })).toBe("string");
    expect(typeof validateQuiz({ ...GOOD, options: ["a", "A", "c", "d"] })).toBe("string");
    expect(typeof validateQuiz({ ...GOOD, options: ["a", "b", "c", "None of the above"] })).toBe("string");
    expect(typeof validateQuiz({ ...GOOD, options: ["a", "b", "c", Array(26).fill("w").join(" ")] })).toBe("string");
    expect(typeof validateQuiz({ ...GOOD, correct_index: 4 })).toBe("string");
    expect(typeof validateQuiz({ ...GOOD, question: "" })).toBe("string");
    expect(validateQuiz(GOOD)).toEqual({ question: GOOD.question, options: GOOD.options, correctIndex: 1 });
  });

  it("shuffle preserves the correct answer for many seeds", () => {
    const q = { question: "q", options: ["w", "x", "y", "z"], correctIndex: 2 };
    for (let s = 0; s < 50; s++) {
      let seed = s + 1;
      const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
      const r = shuffleQuiz(q, rnd);
      expect(r.options[r.correctIndex]).toBe("y");
      expect([...r.options].sort()).toEqual(q.options);
    }
  });

  it("parses FUN_SOURCES", () => {
    expect(parseSources("channel:@MrBeast, keyword:satisfying,hashtag:shorts,bogus:x,")).toEqual([
      { kind: "channel", value: "@MrBeast" },
      { kind: "keyword", value: "satisfying" },
      { kind: "hashtag", value: "shorts" },
    ]);
  });
});
