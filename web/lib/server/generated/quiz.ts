// Fun-quiz generation with fallback ladder:
// store transcript → in-memory/Apify transcript → LLM transcript quiz → LLM metadata quiz → NO_TRANSCRIPT_POLICY.
import Anthropic from "@anthropic-ai/sdk";
import { zodOutputFormat } from "@anthropic-ai/sdk/helpers/zod";
import { z } from "zod/v4";
import type { FetchLike } from "./apify";
import { overCap, recordSpend } from "./spend";
import { getTranscript, type Transcript } from "./transcripts";
import { metaById } from "./discover";

export const MODEL = "claude-opus-5-5";

export const QuizSchema = z.object({
  question: z.string(),
  options: z.array(z.string()),
  correct_index: z.number().int(),
  rationale: z.string(),
});
export type RawQuiz = z.infer<typeof QuizSchema>;
export type FunQuiz = { question: string; options: string[]; correctIndex: number };
export type QuizResult = FunQuiz | { pass: true };

export class QuizPolicyError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "QuizPolicyError";
  }
}

/** Minimal surface of Anthropic used here, so tests can inject a mock. */
export interface QuizClient {
  messages: {
    parse(params: unknown): Promise<{
      stop_reason: string | null;
      parsed_output?: RawQuiz | null;
      usage?: { input_tokens?: number; output_tokens?: number };
    }>;
  };
}

export type CachedTranscriptFn = (videoId: string) => Transcript | null | undefined | Promise<Transcript | null | undefined>;

export interface QuizDeps {
  client?: QuizClient;
  fetch?: FetchLike;
  getCachedTranscript?: CachedTranscriptFn;
  random?: () => number;
}

let defaultClient: QuizClient | null = null;
function client(deps: QuizDeps): QuizClient {
  if (deps.client) return deps.client;
  defaultClient ??= new Anthropic() as unknown as QuizClient;
  return defaultClient;
}

/** Default: the server store's TRANSCRIPTS_PATH loader, imported lazily so tests don't depend on it. */
const defaultCachedTranscript: CachedTranscriptFn = async (id) => {
  try {
    const mod = (await import("../store")) as { getCachedTranscript?: (id: string) => unknown };
    return normalizeStoreTranscript(await mod.getCachedTranscript?.(id));
  } catch {
    return null;
  }
};

/** Accepts either {text, lang, isAutoGenerated} or the store's VideoRow {transcript_text, transcript_lang, transcript_auto}. */
export function normalizeStoreTranscript(v: unknown): Transcript | null {
  if (!v || typeof v !== "object") return null;
  const r = v as Record<string, unknown>;
  const text = typeof r.text === "string" ? r.text : typeof r.transcript_text === "string" ? r.transcript_text : "";
  if (!text.trim()) return null;
  const lang = (r.lang ?? r.transcript_lang) as string | null | undefined;
  const auto = (r.isAutoGenerated ?? r.transcript_auto) as boolean | null | undefined;
  return { text, ...(lang ? { lang } : {}), ...(typeof auto === "boolean" ? { isAutoGenerated: auto } : {}) };
}

const BANNED = /\b(all|none|both|neither) of the above\b/i;

/** Returns a cleaned quiz or a string describing why it is invalid. */
export function validateQuiz(q: RawQuiz | null | undefined): FunQuiz | string {
  if (!q) return "no parsed output";
  const question = q.question?.trim();
  if (!question) return "empty question";
  if (!Array.isArray(q.options) || q.options.length !== 4) return "need exactly 4 options";
  const options = q.options.map((o) => (typeof o === "string" ? o.trim() : ""));
  if (options.some((o) => !o)) return "empty option";
  if (new Set(options.map((o) => o.toLowerCase())).size !== 4) return "duplicate options";
  if (options.some((o) => o.split(/\s+/).length > 25)) return "option over 25 words";
  if (options.some((o) => BANNED.test(o))) return "all/none of the above";
  if (!Number.isInteger(q.correct_index) || q.correct_index < 0 || q.correct_index > 3) return "bad correct_index";
  return { question, options, correctIndex: q.correct_index };
}

/** Fisher-Yates shuffle that tracks the correct answer. */
export function shuffleQuiz(q: FunQuiz, random: () => number = Math.random): FunQuiz {
  const idx = q.options.map((_, i) => i);
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  return { question: q.question, options: idx.map((i) => q.options[i]), correctIndex: idx.indexOf(q.correctIndex) };
}

const RULES = `Write ONE multiple-choice question with exactly 4 options and one correct answer.
Rules:
- Write the question and options in the same language as the source material.
- The question must NOT be answerable from the title alone or from general knowledge; it must require having watched the video.
- Distractors must be plausible and parallel in form and length to the correct answer.
- Never use "all of the above", "none of the above", or similar.
- Each option is at most 25 words.
- Never invent facts: everything in the correct answer must be stated in the source material.
- rationale: one short sentence citing what in the source supports the answer.`;

function transcriptPrompt(t: Transcript, meta: { title?: string; channel?: string }): string {
  const text = t.text.length > 12000 ? t.text.slice(0, 12000) : t.text;
  const asr = t.isAutoGenerated
    ? "\n- The transcript is auto-generated (ASR) and may contain mis-heard words; do not rely on exact spellings or wording of any single phrase; ask about clearly conveyed content."
    : "";
  return `${RULES}${asr}

Video title: ${meta.title ?? "(unknown)"}
Channel: ${meta.channel ?? "(unknown)"}
Transcript language: ${t.lang ?? "(detect from text)"}
<transcript>
${text}
</transcript>`;
}

function metadataPrompt(meta: { title?: string; channel?: string }): string {
  return `No transcript is available. Write a light attention-check question about this YouTube Short using ONLY the metadata below (e.g. which channel posted it, or which of four titles was the one just watched). Distractors must be plausible but clearly not this video's metadata. Never invent facts about the video's content.
- Use the same language as the title.
- Never use "all of the above" or "none of the above".
- Each option is at most 25 words.

Title: ${meta.title}
Channel: ${meta.channel ?? "(unknown)"}`;
}

function llmCostUsd(usage?: { input_tokens?: number; output_tokens?: number }): number {
  const inRate = Number(process.env.LLM_USD_PER_MTOK_IN) || 5;
  const outRate = Number(process.env.LLM_USD_PER_MTOK_OUT) || 25;
  return ((usage?.input_tokens ?? 0) * inRate + (usage?.output_tokens ?? 0) * outRate) / 1e6;
}

function isRetryable(e: unknown): boolean {
  const status = (e as { status?: number })?.status;
  if (status === 429) return true;
  if (typeof status === "number") return false; // other API errors: SDK already retried; move down the ladder
  return true; // parse / JSON / validation errors
}

/** One LLM rung: up to 2 attempts (retry once on refusal / parse failure / max_tokens / 429). */
async function llmQuiz(prompt: string, deps: QuizDeps): Promise<FunQuiz | null> {
  for (let attempt = 0; attempt < 2; attempt++) {
    if (overCap()) return null;
    try {
      const res = await client(deps).messages.parse({
        model: MODEL,
        max_tokens: 1024,
        output_config: { effort: "low", format: zodOutputFormat(QuizSchema) },
        messages: [{ role: "user", content: prompt }],
      });
      recordSpend({ llmUsd: llmCostUsd(res.usage) });
      if (res.stop_reason === "refusal" || res.stop_reason === "max_tokens") continue;
      const v = validateQuiz(res.parsed_output);
      if (typeof v === "string") continue;
      return v;
    } catch (e) {
      if (!isRetryable(e)) return null;
    }
  }
  return null;
}

function policy(): QuizResult {
  const p = process.env.NO_TRANSCRIPT_POLICY ?? "metadata-then-pass";
  if (p === "fail-closed") throw new QuizPolicyError("No quiz could be generated (NO_TRANSCRIPT_POLICY=fail-closed)");
  return { pass: true };
}

export async function generateFunQuiz(
  videoId: string,
  meta?: { title?: string; channel?: string },
  deps: QuizDeps = {},
): Promise<QuizResult> {
  const m = { ...metaById.get(videoId), ...meta };
  const random = deps.random ?? Math.random;

  // Rung 1: teammate's extracted transcripts file (works for custom-list videos with no hand-written quiz).
  let transcript: Transcript | null = null;
  try {
    transcript = normalizeStoreTranscript(await (deps.getCachedTranscript ?? defaultCachedTranscript)(videoId));
  } catch {
    transcript = null;
  }
  if (!transcript?.text?.trim()) transcript = null;

  // Over the daily cap: skip Apify and LLM entirely.
  if (overCap()) return policy();

  // Rung 2: in-memory cache / inflight prefetch / Apify.
  if (!transcript) transcript = await getTranscript(videoId, { fetch: deps.fetch });

  // Rung 3: LLM quiz from transcript.
  if (transcript) {
    const q = await llmQuiz(transcriptPrompt(transcript, m), deps);
    if (q) {
      recordSpend({ quizzes: 1 });
      return shuffleQuiz(q, random);
    }
  }

  // Rung 4: metadata-only quiz.
  const p = process.env.NO_TRANSCRIPT_POLICY ?? "metadata-then-pass";
  if (p === "metadata-then-pass" && m.title?.trim()) {
    const q = await llmQuiz(metadataPrompt(m), deps);
    if (q) {
      recordSpend({ quizzes: 1 });
      return shuffleQuiz(q, random);
    }
  }

  // Rung 5: policy.
  return policy();
}
