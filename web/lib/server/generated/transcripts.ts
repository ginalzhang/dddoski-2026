// Transcript cache + Apify devsef~youtube-transcript-scraper (fields verified 2026-10-16 from the actor .md page).
import { runActor, type FetchLike } from "./apify";
import { overCap } from "./spend";

export const TRANSCRIPT_ACTOR = "devsef~youtube-transcript-scraper";
export const MAX_IDS_PER_RUN = 200;

export interface Transcript {
  text: string;
  lang?: string;
  isAutoGenerated?: boolean;
}

/** null = known to have no transcript (no_transcript/unavailable). Missing key = unknown. */
const cache = new Map<string, Transcript | null>();
const inflight = new Map<string, Promise<void>>();

export function __resetTranscripts() {
  cache.clear();
  inflight.clear();
}

export function cachedTranscript(id: string): Transcript | null | undefined {
  return cache.get(id);
}

interface TranscriptItem {
  videoId?: string;
  status?: string;
  text?: string;
  language?: string;
  isAutoGenerated?: boolean;
}

async function runBatch(ids: string[], fetch?: FetchLike): Promise<void> {
  const perId = Number(process.env.APIFY_TRANSCRIPT_USD_PER_ID) || 0.005;
  const items = await runActor<TranscriptItem>(
    TRANSCRIPT_ACTOR,
    { videoUrls: ids, includeSegments: false },
    { fetch, maxChargeUsd: Math.max(0.05, +(perId * ids.length).toFixed(3)) },
  );
  for (const it of items) {
    if (!it.videoId) continue;
    if (it.status === "ok" && it.text?.trim()) {
      cache.set(it.videoId, { text: it.text, lang: it.language, isAutoGenerated: it.isAutoGenerated });
    } else if (it.status === "no_transcript" || it.status === "unavailable") {
      cache.set(it.videoId, null);
    }
    // blocked / error: leave unknown so a later call may retry.
  }
}

/** Fetch transcripts for unknown IDs in batches of ≤200. Never throws; failures leave IDs unknown. */
export function prefetchTranscripts(ids: string[], deps: { fetch?: FetchLike } = {}): Promise<void> {
  if (overCap() || !process.env.APIFY_TOKEN) return Promise.resolve();
  const todo = [...new Set(ids)].filter((id) => !cache.has(id) && !inflight.has(id));
  const jobs: Promise<void>[] = [];
  for (let i = 0; i < todo.length; i += MAX_IDS_PER_RUN) {
    const chunk = todo.slice(i, i + MAX_IDS_PER_RUN);
    const p = runBatch(chunk, deps.fetch)
      .catch((e) => console.warn("[generated] transcript prefetch failed:", (e as Error)?.message))
      .finally(() => chunk.forEach((id) => inflight.delete(id)));
    chunk.forEach((id) => inflight.set(id, p));
    jobs.push(p);
  }
  // Also wait on any already-inflight IDs the caller asked about.
  for (const id of ids) {
    const p = inflight.get(id);
    if (p && !jobs.includes(p)) jobs.push(p);
  }
  return Promise.all(jobs).then(() => undefined);
}

/** Cache → inflight prefetch → single Apify run. Returns null when unavailable. */
export async function getTranscript(id: string, deps: { fetch?: FetchLike } = {}): Promise<Transcript | null> {
  if (cache.has(id)) return cache.get(id) ?? null;
  await prefetchTranscripts([id], deps);
  return cache.get(id) ?? null;
}
